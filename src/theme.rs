//! Kagero's visual system: a dark workshop lit by warm amber, drawn in pixels.
//!
//! Text uses Kagero Pixel, the app's own bitmap-style font (`assets/fonts`). Font
//! sizes are always whole multiples of one font pixel in *device* pixels, so text is
//! as sharp as the canvas at every display scale. Corners are square and shadows are
//! hard offsets instead of blurs.

use std::sync::atomic::{AtomicU32, Ordering};

use egui::{Color32, CornerRadius, FontFamily, FontId, Margin, Shadow, Stroke, TextStyle, Visuals};

pub const BACKGROUND: Color32 = Color32::from_rgb(0x17, 0x19, 0x1F);
pub const PANEL: Color32 = Color32::from_rgb(0x20, 0x23, 0x2B);
pub const SURFACE: Color32 = Color32::from_rgb(0x2C, 0x30, 0x3A);
pub const SURFACE_HOVER: Color32 = Color32::from_rgb(0x37, 0x3C, 0x48);
pub const BORDER: Color32 = Color32::from_rgb(0x34, 0x38, 0x43);
/// Light edge of raised pixel bevels.
pub const BEVEL_LIGHT: Color32 = Color32::from_rgb(0x4A, 0x4F, 0x5C);
/// Dark edge of raised pixel bevels and hard shadows.
pub const BEVEL_DARK: Color32 = Color32::from_rgb(0x0E, 0x0F, 0x13);
pub const TEXT_SECONDARY: Color32 = Color32::from_rgb(0xA5, 0xA9, 0xB5);
pub const TEXT_PRIMARY: Color32 = Color32::from_rgb(0xF0, 0xEE, 0xE8);
pub const ACCENT: Color32 = Color32::from_rgb(0xFF, 0x9D, 0x42);
pub const ACCENT_PRESSED: Color32 = Color32::from_rgb(0xF0, 0x6B, 0x35);
pub const SUCCESS: Color32 = Color32::from_rgb(0x75, 0xC7, 0xB5);
/// Deep ember used behind light text for pressed and selected states (readable contrast).
pub const EMBER_DEEP: Color32 = Color32::from_rgb(0x6B, 0x36, 0x1C);
pub const ERROR: Color32 = Color32::from_rgb(0xE8, 0x5D, 0x5D);
/// Text drawn on top of the accent color.
pub const ON_ACCENT: Color32 = Color32::from_rgb(0x1A, 0x14, 0x10);
/// Two shades of the transparency checkerboard.
pub const CHECKER_LIGHT: Color32 = Color32::from_rgb(0x4A, 0x4E, 0x58);
pub const CHECKER_DARK: Color32 = Color32::from_rgb(0x3A, 0x3D, 0x46);

/// Corner radius of every frame: square, like pixels.
pub const RADIUS: u8 = 0;

/// Kagero Pixel, generated by `scripts/build-font.py`.
const PIXEL_FONT: &[u8] = include_bytes!("../assets/fonts/KageroPixel.ttf");
/// Font size (points) at which one font pixel is one point: ascent 11 + descent 2.
const FONT_PIXELS: f32 = 13.0;

/// Size of one font pixel in points (f32 bits); see [`sync_pixel_scale`].
static FONT_UNIT_BITS: AtomicU32 = AtomicU32::new(0x3F80_0000); // 1.0

/// One font pixel, in points, for `pixels_per_point`: a whole number of device
/// pixels (at least one), as close to one point as possible.
pub fn font_unit(pixels_per_point: f32) -> f32 {
    let ppp = if pixels_per_point.is_finite() && pixels_per_point > 0.0 {
        pixels_per_point
    } else {
        1.0
    };
    ppp.round().max(1.0) / ppp
}

/// The pixel font at `scale` × its base size (1 = body text, 2 = headings, …).
pub fn font(scale: u32) -> FontId {
    let unit = f32::from_bits(FONT_UNIT_BITS.load(Ordering::Relaxed));
    FontId::new(
        FONT_PIXELS * unit * scale.max(1) as f32,
        FontFamily::Proportional,
    )
}

/// Applies the Kagero style to an egui context.
pub fn apply(ctx: &egui::Context) {
    install_fonts(ctx);

    let mut visuals = Visuals::dark();
    visuals.override_text_color = None;
    visuals.panel_fill = PANEL;
    visuals.window_fill = PANEL;
    visuals.extreme_bg_color = BACKGROUND;
    visuals.faint_bg_color = SURFACE;
    visuals.code_bg_color = SURFACE;
    visuals.window_stroke = Stroke::new(1.0_f32, BEVEL_LIGHT);
    visuals.window_corner_radius = CornerRadius::ZERO;
    visuals.menu_corner_radius = CornerRadius::ZERO;
    // Hard pixel shadows: offset, no blur.
    visuals.window_shadow = Shadow {
        offset: [4, 4],
        blur: 0,
        spread: 0,
        color: Color32::from_black_alpha(150),
    };
    visuals.popup_shadow = Shadow {
        offset: [3, 3],
        blur: 0,
        spread: 0,
        color: Color32::from_black_alpha(150),
    };
    visuals.handle_shape = egui::style::HandleShape::Rect { aspect_ratio: 0.6 };
    visuals.hyperlink_color = ACCENT;
    visuals.selection.bg_fill = EMBER_DEEP;
    visuals.selection.stroke = Stroke::new(1.0_f32, ACCENT);
    visuals.error_fg_color = ERROR;
    visuals.warn_fg_color = ACCENT;
    visuals.slider_trailing_fill = true;

    let radius = CornerRadius::same(RADIUS);
    let w = &mut visuals.widgets;
    w.noninteractive.bg_fill = PANEL;
    w.noninteractive.weak_bg_fill = PANEL;
    w.noninteractive.bg_stroke = Stroke::new(1.0_f32, BORDER);
    w.noninteractive.fg_stroke = Stroke::new(1.0_f32, TEXT_SECONDARY);
    w.noninteractive.corner_radius = radius;

    // Buttons sit in a dark pixel outline, like keys on a keyboard.
    w.inactive.bg_fill = SURFACE;
    w.inactive.weak_bg_fill = SURFACE;
    w.inactive.bg_stroke = Stroke::new(1.0_f32, BEVEL_DARK);
    w.inactive.fg_stroke = Stroke::new(1.0_f32, TEXT_PRIMARY);
    w.inactive.corner_radius = radius;

    w.hovered.bg_fill = SURFACE_HOVER;
    w.hovered.weak_bg_fill = SURFACE_HOVER;
    w.hovered.bg_stroke = Stroke::new(1.0_f32, ACCENT);
    w.hovered.fg_stroke = Stroke::new(1.0_f32, TEXT_PRIMARY);
    w.hovered.corner_radius = radius;
    w.hovered.expansion = 0.0;

    w.active.bg_fill = EMBER_DEEP;
    w.active.weak_bg_fill = EMBER_DEEP;
    w.active.bg_stroke = Stroke::new(1.0_f32, ACCENT);
    // egui also uses this color for `strong()` text, so it must stay light.
    w.active.fg_stroke = Stroke::new(1.0_f32, TEXT_PRIMARY);
    w.active.corner_radius = radius;
    w.active.expansion = 0.0;

    w.open.bg_fill = SURFACE_HOVER;
    w.open.weak_bg_fill = SURFACE_HOVER;
    w.open.bg_stroke = Stroke::new(1.0_f32, BEVEL_DARK);
    w.open.fg_stroke = Stroke::new(1.0_f32, TEXT_PRIMARY);
    w.open.corner_radius = radius;

    ctx.set_visuals(visuals);

    ctx.style_mut(|style| {
        style.spacing.item_spacing = egui::vec2(6.0, 6.0);
        style.spacing.button_padding = egui::vec2(8.0, 4.0);
        style.spacing.menu_margin = Margin::same(4);
        style.spacing.window_margin = Margin::same(12);
        style.spacing.interact_size.y = 22.0;
        style.spacing.icon_width = 12.0;
        style.spacing.icon_width_inner = 6.0;
        style.spacing.scroll = egui::style::ScrollStyle::solid();
        style.spacing.scroll.bar_width = 8.0;
        style.spacing.scroll.handle_min_length = 16.0;
    });
    sync_pixel_scale(ctx);
}

/// Re-snaps the text sizes when the display scale changes (e.g. the window moved
/// to another monitor). Cheap when nothing changed; call it every frame.
pub fn sync_pixel_scale(ctx: &egui::Context) {
    let unit = font_unit(ctx.pixels_per_point());
    FONT_UNIT_BITS.store(unit.to_bits(), Ordering::Relaxed);
    let body = ctx
        .style()
        .text_styles
        .get(&TextStyle::Body)
        .map(|f| f.size);
    if body == Some(FONT_PIXELS * unit) {
        return;
    }
    let size = |scale: f32| FONT_PIXELS * unit * scale;
    ctx.style_mut(|style| {
        style.text_styles = [
            (
                TextStyle::Heading,
                FontId::new(size(2.0), FontFamily::Proportional),
            ),
            (
                TextStyle::Body,
                FontId::new(size(1.0), FontFamily::Proportional),
            ),
            (
                TextStyle::Button,
                FontId::new(size(1.0), FontFamily::Proportional),
            ),
            (
                TextStyle::Small,
                FontId::new(size(1.0), FontFamily::Proportional),
            ),
            (
                TextStyle::Monospace,
                FontId::new(size(1.0), FontFamily::Monospace),
            ),
        ]
        .into();
    });
}

/// Kagero Pixel first; egui's default fonts and a system Japanese font (for "陽炎",
/// read from the local Windows installation and never redistributed) as fallbacks
/// for characters the pixel font doesn't have.
fn install_fonts(ctx: &egui::Context) {
    let mut fonts = egui::FontDefinitions::default();
    fonts.font_data.insert(
        "kagero-pixel".to_owned(),
        std::sync::Arc::new(egui::FontData::from_static(PIXEL_FONT)),
    );
    for family in [FontFamily::Proportional, FontFamily::Monospace] {
        fonts
            .families
            .entry(family)
            .or_default()
            .insert(0, "kagero-pixel".to_owned());
    }
    let candidates = [
        r"C:\Windows\Fonts\YuGothM.ttc",
        r"C:\Windows\Fonts\msgothic.ttc",
        r"C:\Windows\Fonts\meiryo.ttc",
    ];
    for path in candidates {
        let Ok(meta) = std::fs::metadata(path) else {
            continue;
        };
        if meta.len() > 64 * 1024 * 1024 {
            continue;
        }
        match std::fs::read(path) {
            Ok(bytes) => {
                fonts.font_data.insert(
                    "jp-fallback".to_owned(),
                    std::sync::Arc::new(egui::FontData::from_owned(bytes)),
                );
                for family in [FontFamily::Proportional, FontFamily::Monospace] {
                    fonts
                        .families
                        .entry(family)
                        .or_default()
                        .push("jp-fallback".to_owned());
                }
                break;
            }
            Err(e) => tracing::debug!("font {path} not loaded: {e}"),
        }
    }
    ctx.set_fonts(fonts);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn font_pixels_are_whole_device_pixels() {
        for ppp in [1.0_f32, 1.25, 1.5, 1.75, 2.0, 2.5, 3.0, 0.8] {
            let device = font_unit(ppp) * ppp;
            assert!((device - device.round()).abs() < 1e-4, "{ppp}: {device}");
            assert!(device >= 1.0);
        }
        assert_eq!(font_unit(1.0), 1.0);
        assert_eq!(font_unit(f32::NAN), 1.0);
    }

    #[test]
    fn the_pixel_font_parses_and_covers_the_interface() {
        let face = ab_glyph::FontRef::try_from_slice(PIXEL_FONT).expect("valid font");
        use ab_glyph::Font as _;
        for ch in (' '..='~').chain(
            "·×…—–°“”→←·АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя".chars(),
        ) {
            assert_ne!(face.glyph_id(ch).0, 0, "missing {ch:?}");
        }
    }
}
